const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const FFMPEG = "H:/!Desktop/Venray Studios/Coding/Tools/ffmpeg/ffmpeg-master-latest-win64-gpl/bin/ffmpeg.exe";
const SCHLAG = 0.5;
const quelle = n => path.join(__dirname, "clips", n + ".mp4");

const PLAN = require("./plan.js");

const args = ["-v", "error", "-y"];
const filter = [];
const namen = [];
let schlaege = 0;
PLAN.forEach(([clip, start, laenge, o = {}], i) => {
  const dauer = laenge * SCHLAG + (o.ende ? 1.6 : 0);
  schlaege += laenge;
  args.push("-i", quelle(clip));
  const tempo = o.tempo || 1;
  const z0 = o.z0 || o.z || 1, z1 = o.z1 || o.z || z0;
  const fx = o.fx === undefined ? 0.5 : o.fx, fy = o.fy === undefined ? 0.5 : o.fy;
  const stoss = o.stoss === undefined ? 0.07 : o.stoss;
  const wackeln = o.wackeln || 0;
  const zoom = `((${z0})+((${z1})-(${z0}))*((on/30)/${dauer.toFixed(3)}))*(1+${stoss}*exp(-(on/30)*11))`;
  const wx = wackeln ? `+${wackeln}*sin((on/30)*71)*exp(-(on/30)*5)` : "";
  const wy = wackeln ? `+${wackeln}*cos((on/30)*63)*exp(-(on/30)*5)` : "";
  let f = `[${i}:v]trim=start=${start}:duration=${(dauer * tempo + 0.2).toFixed(3)},setpts=(PTS-STARTPTS)/${tempo}`;
  if (o.ende || o.halten) f += `,tpad=stop_mode=clone:stop_duration=4`;
  f += `,fps=30,trim=duration=${dauer.toFixed(3)},setpts=PTS-STARTPTS`;
  f += `,scale=3840:2160:flags=bicubic`;
  f += `,zoompan=z='${zoom}':x='(iw-iw/zoom)*${fx}${wx}':y='(ih-ih/zoom)*${fy}${wy}':d=1:s=1920x1080:fps=30`;
  f += `,setsar=1,format=yuv420p`;
  if (o.blitz) f += `,fade=t=in:st=0:d=${o.blitz === true ? 0.25 : o.blitz}:color=white`;
  if (o.schwarz) f += `,fade=t=in:st=0:d=0.35:color=black`;
  f += `[v${i}]`;
  filter.push(f);
  namen.push(`[v${i}]`);
});
const textIndex = PLAN.length;
args.push("-loop", "1", "-t", "6", "-i", path.join(__dirname, "endtext.png"));
const letzter = PLAN[PLAN.length - 1];
const startEnde = (schlaege - letzter[2]) * SCHLAG;
filter.push(`${namen.join("")}concat=n=${PLAN.length}:v=1:a=0[film]`);
filter.push(`[${textIndex}:v]format=rgba,fade=t=in:st=0:d=0.3:alpha=1,setpts=PTS-STARTPTS+${(startEnde + 1.0).toFixed(3)}/TB[text]`);
filter.push(`[film][text]overlay=0:0:enable='gte(t,${(startEnde + 1.0).toFixed(3)})':eof_action=pass,format=yuv420p[ausgang]`);
const ziel = path.join(__dirname, process.env.ZIEL || "trailer.mp4");
args.push("-filter_complex", filter.join(";"), "-map", "[ausgang]", "-an", "-c:v", "libx264", "-crf", "16", "-preset", "slow", "-pix_fmt", "yuv420p", "-r", "30", "-movflags", "+faststart", ziel);
execFileSync(FFMPEG, args, { stdio: "inherit", maxBuffer: 1 << 26 });
console.log("Schlaege: " + schlaege + ", Laenge " + (schlaege * SCHLAG + 1.6).toFixed(2) + " s");
